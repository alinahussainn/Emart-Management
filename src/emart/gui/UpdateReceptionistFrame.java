    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if(!validateInputs()){
            return;
        }
        try{
           String userid =jcReceptionistId.getSelectedItem().toString();
           boolean result = ReceptionistDAO.updatePassword(userid, Password);
           if(result){
               JOptionPane.showMessageDialog(null, "pasword changed successfully");
               clearText();
               jcReceptionistId.setSelectedIndex(0);
               return;
           }  
           JOptionPane.showMessageDialog(null, "pasword not changed try again later");
             clearText(); 
           
        }catch(SQLException e){
            JOptionPane.showMessageDialog(null,"DB error","error",JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

